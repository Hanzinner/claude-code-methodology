#!/usr/bin/env python3
"""abbr-guard: unexpanded abbreviations are flagged; expanded / whitelisted / glossary / used-by-human stay silent;
--build-vocab learns the human's own abbreviations. AG=<path> tests another copy. Sandbox: temp HOME, no config."""
import json, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.realpath(__file__))
AG = os.environ.get("AG", os.path.join(HERE, "..", "hooks", "abbr-guard.py"))
T = tempfile.mkdtemp(prefix="ag-test-")
GLOS = f"{T}/glossary.md"
open(GLOS, "w").write("# terms\n\n## CONFIRMED\n- TLS, SIEM — known\n\n## UNSURE\n- XDR\n")
P = F = 0
n = 0


def run(user, asst_list, glossary="", home=None, extra=()):
    global n
    n += 1
    home = home or f"{T}/h{n}"; os.makedirs(home, exist_ok=True)
    tp = f"{home}/t.jsonl"
    with open(tp, "w") as f:
        f.write(json.dumps({"type": "user", "message": {"content": user}}) + "\n")
        for a in asst_list:
            f.write(json.dumps({"type": "assistant", "message": {"content": [{"type": "text", "text": a}]}}) + "\n")
    env = {**os.environ, "HOME": home, "CLAUDE_METHODOLOGY_CONF": "/nonexistent", "CCM_GLOSSARY": glossary, "CCM_HUMAN_NAME": "Sam"}
    r = subprocess.run([sys.executable, AG, *extra], input=json.dumps({"session_id": "sidA", "transcript_path": tp}),
                       capture_output=True, text=True, env=env)
    fl = f"{home}/.claude/abbr-guard-flags/sidA"
    return (open(fl).read() if os.path.exists(fl) else ""), r


def t(name, want, *a, **k):
    global P, F
    fl, r = run(*a, **k)
    good = r.returncode == 0 and ((want is None and fl == "") or (want is not None and fl.startswith("⚠️ [abbr-guard]") and want in fl))
    if good: P += 1
    else: F += 1; print(f"FAIL: {name}: rc={r.returncode} flag={fl!r} {r.stderr[:150]}")


t("unexpanded abbreviation → flag", "GUID", "check the id", ["The GUID is stored in the table."])
t("expanded 'ABC (…)' → silent", None, "check the id", ["The GUID (globally unique identifier) is stored."])
t("expanded '… (ABC)' → silent", None, "x", ["The globally unique identifier (GUID) is stored."])
t("'stands for' → silent", None, "x", ["GUID stands for globally unique identifier, and it is stored."])
t("whitelisted (PDF, AI) → silent", None, "x", ["The PDF was generated by the AI tool."])
t("the human used it → silent", None, "what is the GUID of the user?", ["The GUID is 42."])
t("file name / id with digits → silent", None, "x", ["See README.md and E4 for COM1."])
t("inside code / quotes → silent", None, "x", ["Run `WMI` here.\n\n```\nTCP RFC\n```\n\nDone."])
t("in the glossary CONFIRMED → silent", None, "x", ["TLS and SIEM are configured."], glossary=GLOS)
t("glossary UNSURE section does not count", "XDR", "x", ["XDR is enabled."], glossary=GLOS)
t("expanded in an earlier assistant turn → silent", None, "x", ["Message passing interface (MPI) is used.", "MPI is fast."])
home = f"{T}/vocab"
for i in range(3):
    run(f"please configure the SOAR playbook {i}", ["ok"], home=home)
    # each run is a separate transcript; build-vocab counts sessions where the human used the term
os.makedirs(f"{home}/.claude/projects/p", exist_ok=True)
for i in range(3):
    with open(f"{home}/.claude/projects/p/s{i}.jsonl", "w") as f:
        f.write(json.dumps({"type": "user", "message": {"content": "tune the SOAR playbook"}}) + "\n")
r = subprocess.run([sys.executable, AG, "--build-vocab"], capture_output=True, text=True,
                   env={**os.environ, "HOME": home, "CLAUDE_METHODOLOGY_CONF": "/nonexistent"})
ok = r.returncode == 0 and "SOAR" in open(f"{home}/.claude/abbr-user-vocab.json").read()
if ok: P += 1
else: F += 1; print("FAIL: --build-vocab", r.stdout, r.stderr[:200])
t("vocab-learned abbreviation → silent", None, "x", ["SOAR is wired in."], home=home)
print(f"abbr-guard: {P} pass, {F} fail"); sys.exit(1 if F else 0)
